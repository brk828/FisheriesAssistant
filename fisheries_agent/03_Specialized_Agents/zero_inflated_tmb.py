import subprocess
import os

def run_zero_inflated_model(csv_path: str, response_var: str, predictor_vars: list, zero_inflation_formula: str = "~1"):
    """
    Constructs and executes a safe glmmTMB R script dynamically for count data.
    """
    predictors_str = " + ".join(predictor_vars)
    
    # 1. Assemble clean R Script using best-practice templates
    r_script_content = f"""
    library(glmmTMB)
    
    # Load dataset
    data <- read.csv("{csv_path}")
    
    # Fit Zero-Inflated Negative Binomial Model
    model <- glmmTMB({response_var} ~ {predictors_str}, 
                      ziformula = {zero_inflation_formula}, 
                      family = nbinom2, 
                      data = data)
    
    # Export summaries cleanly for Python to intercept
    sink("tmb_model_output.txt")
    print(summary(model))
    cat("\\n--- CONFIDENCE INTERVALS ---\\n")
    print(confint(model))
    sink()
    
    # Diagnostic plots can save straight to directories for user review via SSH
    png("tmb_diagnostics.png", width=800, height=600)
    plot(residuals(model) ~ fitted(model))
    dev.off()
    """
    
    with open("temp_run_model.R", "w") as f:
        f.write(r_script_content)
        
    # 2. Execute locally via Rscript
    try:
        result = subprocess.run(["Rscript", "temp_run_model.R"], capture_output=True, text=True, check=True)
        
        # Read structured metrics generated by R
        if os.path.exists("tmb_model_output.txt"):
            with open("tmb_model_output.txt", "r") as res_file:
                output_summary = res_file.read()
            return f"Model successfully converged!\n{output_summary}\nDiagnostics saved to 'tmb_diagnostics.png'"
        return "R executed, but output log file was missing."
        
    except subprocess.CalledProcessError as e:
        return f"R script error:\n{e.stderr}"
    finally:
        # Cleanup script wrapper
        if os.path.exists("temp_run_model.R"):
            os.remove("temp_run_model.R")
